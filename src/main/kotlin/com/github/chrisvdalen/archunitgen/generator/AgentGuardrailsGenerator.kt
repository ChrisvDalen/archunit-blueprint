package com.github.chrisvdalen.archunitgen.generator

import com.github.chrisvdalen.archunitgen.model.RuleStatus
import com.github.chrisvdalen.archunitgen.model.RuleSuggestion

/**
 * Turns the same accepted [RuleSuggestion]s that feed [ArchUnitTestGenerator] into guardrails
 * for AI coding agents, so the agent and CI work from one rule set:
 *
 *  - A managed "Architecture rules" section in `AGENTS.md`, `CLAUDE.md` and
 *    `.github/copilot-instructions.md`, telling the agent what the rules are *before* it writes code.
 *  - A Claude Code Stop hook that runs the generated ArchUnit test when the agent tries to finish
 *    and sends violations back to it, so prose rules it ignored still get enforced.
 *
 * Pure Kotlin, no IntelliJ dependency; [GuardrailFileWriter] does the disk I/O.
 */
class AgentGuardrailsGenerator {

    fun generate(suggestions: List<RuleSuggestion>, testFile: GeneratedTestFile): List<GuardrailFile> {
        val accepted = suggestions.filter { it.status == RuleStatus.ACCEPTED }
        val section = renderInstructions(accepted, testFile)

        return INSTRUCTION_FILES.map { GuardrailFile(it, section, WriteMode.MANAGED_SECTION) } +
            GuardrailFile(HOOK_SCRIPT_PATH, renderHookScript(testFile), WriteMode.OVERWRITE) +
            GuardrailFile(CLAUDE_SETTINGS_PATH, CLAUDE_SETTINGS, WriteMode.CREATE_ONLY)
    }

    // ── Private helpers ───────────────────────────────────────────────────────

    private fun renderInstructions(accepted: List<RuleSuggestion>, testFile: GeneratedTestFile): String {
        val fqn = "${testFile.packageName}.${testFile.className}"
        return buildString {
            appendLine(ManagedSection.BEGIN)
            appendLine("## Architecture rules")
            appendLine()
            appendLine("These rules are enforced by the ArchUnit test `$fqn`; a change that breaks one fails the build.")
            appendLine("Follow them when you write code. If a rule fails, change the code, not the test: do not edit,")
            appendLine("weaken or delete `${testFile.className}`. If a rule seems wrong for the task, stop and ask.")
            appendLine()
            appendLine("Check them before you finish:")
            appendLine()
            appendLine("- Gradle: `./gradlew test --tests $fqn`")
            appendLine("- Maven: `./mvnw test -Dtest=${testFile.className}`")
            accepted.forEach { s ->
                appendLine()
                appendLine("### ${s.title}")
                appendLine()
                appendLine(s.description)
                appendLine()
                appendLine("Why: ${s.rationale}")
                appendLine()
                appendLine("```java")
                s.ruleTemplate.codeLines.forEach { appendLine(it) }
                appendLine("```")
            }
            append(ManagedSection.END)
        }
    }

    private fun renderHookScript(testFile: GeneratedTestFile): String {
        val fqn = "${testFile.packageName}.${testFile.className}"
        return """
            |#!/usr/bin/env sh
            |# Generated by ArchUnit Rule Generator. Claude Code Stop hook: keeps the agent working
            |# while the architecture rules in $fqn fail. Re-generate instead of editing.
            |
            |input=$(cat)
            |
            |# The agent is already fixing a failure reported by this hook: let it stop to avoid a loop.
            |if printf '%s' "${'$'}input" | grep -q '"stop_hook_active"[[:space:]]*:[[:space:]]*true'; then
            |  exit 0
            |fi
            |
            |cd "${'$'}{CLAUDE_PROJECT_DIR:-.}" || exit 0
            |
            |# Nothing to check when no Java source changed.
            |if git rev-parse --is-inside-work-tree >/dev/null 2>&1 &&
            |   [ -z "$(git status --porcelain -- '*.java')" ]; then
            |  exit 0
            |fi
            |
            |if [ -x ./gradlew ]; then
            |  set -- ./gradlew test --tests '$fqn' -q
            |elif [ -x ./mvnw ]; then
            |  set -- ./mvnw test -q -Dtest='${testFile.className}' -Dsurefire.failIfNoSpecifiedTests=false
            |elif [ -f pom.xml ] && command -v mvn >/dev/null 2>&1; then
            |  set -- mvn test -q -Dtest='${testFile.className}' -Dsurefire.failIfNoSpecifiedTests=false
            |elif command -v gradle >/dev/null 2>&1; then
            |  set -- gradle test --tests '$fqn' -q
            |else
            |  exit 0
            |fi
            |
            |if output=$("$@" 2>&1); then
            |  exit 0
            |fi
            |
            |violations=$(printf '%s\n' "${'$'}output" | grep -v '^[[:space:]]*at ' | grep -A 15 'Architecture Violation' | head -n 40)
            |{
            |  echo "Architecture rules in $fqn failed (command: $*)."
            |  echo "Fix the code so the rules pass. Do not edit, weaken or delete the test."
            |  echo
            |  if [ -n "${'$'}violations" ]; then
            |    printf '%s\n' "${'$'}violations"
            |  else
            |    printf '%s\n' "${'$'}output" | tail -n 60
            |  fi
            |} >&2
            |exit 2
            |""".trimMargin()
    }

    companion object {
        val INSTRUCTION_FILES = listOf("AGENTS.md", "CLAUDE.md", ".github/copilot-instructions.md")
        const val HOOK_SCRIPT_PATH = ".claude/hooks/archunit-check.sh"
        const val CLAUDE_SETTINGS_PATH = ".claude/settings.json"

        val CLAUDE_SETTINGS = """
            |{
            |  "hooks": {
            |    "Stop": [
            |      {
            |        "hooks": [
            |          {
            |            "type": "command",
            |            "command": "sh \"${'$'}CLAUDE_PROJECT_DIR/$HOOK_SCRIPT_PATH\"",
            |            "timeout": 600
            |          }
            |        ]
            |      }
            |    ]
            |  }
            |}
            |""".trimMargin()
    }
}

data class GuardrailFile(
    /** Relative path from project root, e.g. `.claude/settings.json`. */
    val relativePath: String,
    val content: String,
    val mode: WriteMode,
)

enum class WriteMode {
    /** Replace only the plugin's marked section, keeping whatever the team wrote around it. */
    MANAGED_SECTION,

    /** The file belongs to the plugin; always rewrite it. */
    OVERWRITE,

    /** Never touch an existing file (the user merges by hand). */
    CREATE_ONLY;

    /** What to write given the file's current [existing] content, or `null` to leave it alone. */
    fun contentToWrite(existing: String?, content: String): String? = when (this) {
        MANAGED_SECTION -> ManagedSection.merge(existing, content)
        OVERWRITE -> content
        CREATE_ONLY -> if (existing == null) content else null
    }
}

/** Marker-delimited block the plugin owns inside a file it shares with the user. */
object ManagedSection {
    const val BEGIN = "<!-- archunit-rule-generator:begin -->"
    const val END = "<!-- archunit-rule-generator:end -->"

    /** Returns [existing] with its managed block replaced by [section], or appended when absent. */
    fun merge(existing: String?, section: String): String {
        if (existing.isNullOrBlank()) return "$section\n"

        val start = existing.indexOf(BEGIN)
        val end = if (start >= 0) existing.indexOf(END, start) else -1
        if (start < 0 || end < 0) return "${existing.trimEnd()}\n\n$section\n"

        return existing.substring(0, start) + section + existing.substring(end + END.length)
    }
}
